
import base64
from email.mime.text import MIMEText
from pathlib import Path

from google.auth.transport.requests import Request
from google.oauth2.credentials import Credentials
from google_auth_oauthlib.flow import InstalledAppFlow
from googleapiclient.discovery import build


class EmailNotificationService:

    ROOT = Path(__file__).resolve().parents[2]

    CREDENTIALS_FILE = ROOT / "credentials" / "gmail_credentials.json"
    TOKEN_FILE = ROOT / "credentials" / "sender_token.json"

    SCOPES = ["https://www.googleapis.com/auth/gmail.send"]

    SENDER_EMAIL = "detectioninsiderthreat@gmail.com"

    def __init__(self):
        self.service = None

    def authenticate(self):

        credentials = None

        if self.TOKEN_FILE.exists():
            credentials = Credentials.from_authorized_user_file(
                str(self.TOKEN_FILE),
                self.SCOPES
            )

        if credentials and credentials.expired and credentials.refresh_token:
            credentials.refresh(Request())

        if not credentials or not credentials.valid:

            flow = InstalledAppFlow.from_client_secrets_file(
                str(self.CREDENTIALS_FILE),
                self.SCOPES
            )

            credentials = flow.run_local_server(port=0)

            self.TOKEN_FILE.write_text(
                credentials.to_json(),
                encoding="utf-8"
            )

        self.service = build(
            "gmail",
            "v1",
            credentials=credentials
        )

        return True

    def send_security_alert(self, employee_email, email_data, analysis):
        risk_level = str(
            analysis.get("risk_level", "")
        ).strip().upper()

        allowed_risks = {"MEDIUM", "HIGH", "CRITICAL"}

        if risk_level not in allowed_risks:
            return {
                "sent": False,
                "reason": "Notification is not required for this risk level."
            }

        if self.service is None:
            self.authenticate()

        subject = email_data.get("subject", "Unknown subject")
        sender = email_data.get("sender", "Unknown sender")

        indicators = analysis.get(
            "indicators",
            analysis.get("suspicious_indicators", [])
        )

        if isinstance(indicators, list):
            indicator_text = "\n".join(
                f"- {item}" for item in indicators
            )
        else:
            indicator_text = str(indicators)

        reason = analysis.get(
            "reason",
            analysis.get("note", "Potential security threat detected.")
        )
        subject_by_risk = {
            "MEDIUM": "SECURITY WARNING: Suspicious Email Detected",
            "HIGH": "SECURITY ALERT: High-Risk Email Detected",
            "CRITICAL": "CRITICAL SECURITY ALERT: Immediate Attention Required",
        }

        recommended_action = {
            "MEDIUM": "Exercise caution. Do not click suspicious links or share sensitive information. Verify the sender through official channels.",
            "HIGH": "Do not interact with this email. Do not click links or share credentials. Contact your IT security team.",
            "CRITICAL": "Do not interact with this email. Contact your IT security team immediately and follow your organization's incident response procedure.",
        }
        body = f"""
Dear Employee,

Our Insider Threat Detection System has identified a potentially
fraudulent or suspicious email in your mailbox.

DETECTED EMAIL DETAILS

Original Subject: {subject}
Original Sender: {sender}

Risk Level: {risk_level}

WHY WAS THIS EMAIL FLAGGED?

{indicator_text}

AI ANALYSIS:

{reason}

RECOMMENDED ACTION:
{recommended_action[risk_level]}

1. Do not click links in the suspicious email.
2. Do not download unexpected attachments.
3. Do not share passwords, OTPs, or financial information.
4. Verify the message with your IT or HR department
   through an official communication channel.

This is an automated security notification generated by
the Insider Threat Detection System.

Stay safe,
Insider Threat Detection System
"""

        message = MIMEText(body)

        message["to"] = employee_email
        message["from"] = self.SENDER_EMAIL
        message["subject"] = subject_by_risk[risk_level]

        encoded_message = base64.urlsafe_b64encode(
            message.as_bytes()
        ).decode()

        result = self.service.users().messages().send(
            userId="me",
            body={"raw": encoded_message}
        ).execute()

        return {
            "sent": True,
            "message_id": result.get("id"),
            "recipient": employee_email,
            "risk_level": risk_level
        }
